<#
.SYNOPSIS
    Refreshes backend/Config/DocsPublishedPages.txt from the live docs.cipp.app index.
.DESCRIPTION
    The docs search MCP tool (SearchDocs / GetDoc) links every result back to docs.cipp.app. A
    page can exist in docs/ without being published - drafts stay in SUMMARY.md, and the
    legacy tree is hidden from nav - so linking straight from the file path would hand callers
    URLs that 404. docs.cipp.app/llms.txt is the only authoritative list of what is live, and
    this script snapshots its slugs so the check stays offline at runtime.

    Run it when pages are published or unpublished. The diff should be small; a large one usually
    means the docs were restructured, in which case check Get-CippDocLink's slug derivation still
    holds (Tests/Mcp/CippDocs.Tests.ps1 pins it).
.EXAMPLE
    pwsh build/tools/Update-DocsPublishedPages.ps1
#>
[CmdletBinding()]
param(
    [string]$Uri = 'https://docs.cipp.app/llms.txt',
    [string]$OutputPath = (Join-Path $PSScriptRoot '../../backend/Config/DocsPublishedPages.txt')
)

$ErrorActionPreference = 'Stop'

Write-Host "Fetching $Uri ..."
$Response = Invoke-WebRequest -Uri $Uri -UseBasicParsing

$Slugs = [System.Collections.Generic.SortedSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
foreach ($Line in ($Response.Content -split '\r?\n')) {
    if ($Line -match 'https://docs\.cipp\.app/([^\s)]+)') {
        $Slug = $Matches[1] -replace '\.md$', ''
        # llms.txt also advertises the site's AI-ask URL template, which is not a page.
        if ($Slug -match '[?#]') { continue }
        $Slugs.Add($Slug) | Out-Null
    }
}

if ($Slugs.Count -lt 100) {
    throw "Only $($Slugs.Count) slugs parsed from $Uri - refusing to overwrite the snapshot with what looks like a failed fetch."
}

$Resolved = [System.IO.Path]::GetFullPath($OutputPath)
$Previous = if (Test-Path -LiteralPath $Resolved) {
    @(Get-Content -LiteralPath $Resolved | Where-Object { $_ -and -not $_.StartsWith('#') })
} else { @() }

$Header = @(
    '# Slugs published on docs.cipp.app, snapshotted from llms.txt.'
    '# Generated by build/tools/Update-DocsPublishedPages.ps1 - do not hand-edit.'
    '# Read by Get-CippDocsPublishedSet so the docs search index never emits a URL that 404s.'
    "# $($Slugs.Count) pages."
)
[System.IO.File]::WriteAllLines($Resolved, @($Header) + @($Slugs), (New-Object System.Text.UTF8Encoding $false))

$Added = @($Slugs | Where-Object { $_ -notin $Previous })
$Removed = @($Previous | Where-Object { -not $Slugs.Contains($_) })

Write-Host "Wrote $($Slugs.Count) slugs to $Resolved"
if ($Previous.Count -gt 0) {
    Write-Host "  added:   $($Added.Count)"
    $Added | Select-Object -First 10 | ForEach-Object { Write-Host "    + $_" }
    Write-Host "  removed: $($Removed.Count)"
    $Removed | Select-Object -First 10 | ForEach-Object { Write-Host "    - $_" }
}
